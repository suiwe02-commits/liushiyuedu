/**
 * 查询单词释义（返回中文翻译）
 */
export const lookupWord = async (word: string): Promise<DictionaryResult | null> => {
  try {
    const cleanWord = word.toLowerCase().replace(/[^a-z]/g, '')
    if (!cleanWord) return null

    // 1. 先查本地缓存
    if (commonTranslations[cleanWord]) {
      return {
        word: cleanWord,
        phonetic: '',
        meanings: [{
          partOfSpeech: '常用词',
          definitions: commonTranslations[cleanWord].map(t => ({ definition: t }))
        }]
      }
    }

    // 2. 使用 MyMemory 翻译 API 获取中文翻译
    try {
      const response = await fetch(
        `${MYMEMORY_API}?q=${encodeURIComponent(cleanWord)}&langpair=en|zh-CN`,
        { signal: AbortSignal.timeout(3000) }
      )
      
      if (response.ok) {
        const data = await response.json()
        if (data.responseStatus === 200 && data.responseData?.translatedText) {
          const chineseTranslation = data.responseData.translatedText
          
          return {
            word: cleanWord,
            phonetic: '',
            meanings: [{
              partOfSpeech: '翻译',
              definitions: [{ definition: chineseTranslation }]
            }]
          }
        }
      }
    } catch (apiError) {
      console.log('Translation API failed, using fallback')
    }

    // 3. 如果 API 失败，返回单词本身作为备选
    return {
      word: cleanWord,
      phonetic: '',
      meanings: [{
        partOfSpeech: '未翻译',
        definitions: [{ definition: cleanWord }]
      }]
    }
  } catch (error) {
    console.error('Error looking up word:', error)
    return null
  }
}

/**
 * 获取单词发音音频URL
 */
export const getWordAudio = async (word: string): Promise<string | null> => {
  // 使用 Google TTS 服务（无需 API Key）
  const cleanWord = word.toLowerCase().replace(/[^a-z]/g, '')
  if (!cleanWord) return null
  
  // 返回 Google 翻译 TTS URL
  return `https://translate.google.com/translate_tts?ie=UTF-8&q=${encodeURIComponent(cleanWord)}&tl=en&client=tw-ob`
}